/**
 * The graph shown by the lifecycle studio, in three views: the exporting states of the csv,
 * the lsm states (including the generated validation states) and the desired states.
 */
import { LsmLifecycle, LsmTransfer, Operation } from "./expand";
import { Metadata } from "./metadata";
import { forEachTransfer, Trigger, XState } from "./model";

export type View = "csv" | "lsm" | "desired";

export type EdgeKind =
    | "create"
    | "auto"
    | "update"
    | "delete"
    | "set"
    | "deployed"
    | "failed"
    | "non_compliant"
    | "validated"
    | "rejected";

export const EDGE_KINDS: readonly EdgeKind[] = ["create", "auto", "update", "delete", "set", "deployed", "failed", "non_compliant", "validated", "rejected"];

export interface EdgeDetail {
    kind: EdgeKind;
    /** The csv state and trigger the transfer comes from */
    state: string;
    trigger: Trigger;
    raw: string;
    validate: boolean;
    rollback: boolean;
    operation: Operation | null;
    description?: string;
}

export interface GraphNode {
    id: string;
    label: string | null;
    stage: string;
    initial: boolean;
    deleted: boolean;
    /** Generated by the factory for a validate() transfer */
    generated: boolean;
    exportsResources: boolean;
    /** No on_delete transfer leaves the state */
    protected: boolean;
    /** Kinds of transfers that loop back on the state */
    selfLoops: EdgeKind[];
    desiredState: string | null;
    title: string;
}

export interface GraphEdge {
    id: string;
    source: string;
    target: string;
    details: EdgeDetail[];
}

export interface Stage {
    id: string;
    name: string;
    description?: string;
    order: number;
}

export interface Graph {
    view: View;
    nodes: GraphNode[];
    edges: GraphEdge[];
    stages: Stage[];
}

const TRIGGER_KIND: Record<Trigger, EdgeKind> = {
    on_create: "create",
    on_auto: "auto",
    on_update: "update",
    on_delete: "delete",
    on_api_set_state: "set",
    on_deployed: "deployed",
    on_failed: "failed",
    on_non_compliant: "non_compliant",
};

/**
 * The stage of a csv state: web_stage, or its desired state.  Without web_stage, the states
 * without current attribute set (entry and end of the lifecycle) are not part of any stage.
 */
export function stageOf(x: XState): string {
    if (x.annotations.web_stage) {
        return x.annotations.web_stage;
    }
    return x.current === null ? "" : x.desiredState;
}

function addEdge(edges: Map<string, GraphEdge>, source: string, target: string, detail: EdgeDetail): void {
    const id = `${source}>${target}`;
    const edge = edges.get(id) ?? { id, source, target, details: [] };
    if (!edge.details.some((d) => d.kind === detail.kind && d.trigger === detail.trigger && d.raw === detail.raw && d.state === detail.state)) {
        edge.details.push(detail);
    }
    edges.set(id, edge);
}

function stagesFor(allUsed: string[], metadata: Metadata): Stage[] {
    const used = allUsed.filter((id) => id !== "");
    const declared = metadata.stages;
    const result: Stage[] = declared
        .filter((s) => used.includes(s.id))
        .map((s, i) => ({ id: s.id, name: s.name ?? s.id, description: s.description, order: s.column !== undefined ? s.column * 100 + (s.row ?? 0) : i }));
    const offset = result.length;
    used.filter((id) => !declared.some((s) => s.id === id)).forEach((id, i) => result.push({ id, name: id, order: 1000 + offset + i }));
    return result.sort((a, b) => a.order - b.order);
}

function transferKinds(t: LsmTransfer): [string, EdgeKind, Operation | null][] {
    const result: [string, EdgeKind, Operation | null][] = [];
    if (t.resourceBased) {
        result.push([t.target, "deployed", t.targetOperation]);
        if (t.error) {
            result.push([t.error, "failed", t.errorOperation]);
        }
        if (t.nonCompliant) {
            result.push([t.nonCompliant, "non_compliant", t.nonCompliantOperation]);
        }
        return result;
    }
    if (t.validate) {
        result.push([t.target, "validated", t.targetOperation]);
        if (t.error) {
            result.push([t.error, "rejected", t.errorOperation]);
        }
        return result;
    }
    const kind: EdgeKind = t.apiSetState ? "set" : t.onUpdate ? "update" : t.onDelete ? "delete" : t.origin.trigger === "on_create" ? "create" : "auto";
    result.push([t.target, kind, t.targetOperation]);
    return result;
}

export function buildGraph(view: View, xStates: readonly XState[], lifecycle: LsmLifecycle, metadata: Metadata): Graph {
    const edges = new Map<string, GraphEdge>();
    const nodes: GraphNode[] = [];
    const byName = new Map(xStates.map((x) => [x.name, x]));
    const initial = new Set([lifecycle.initialState, ...lifecycle.alternativeInitialStates]);
    const deletable = new Set(lifecycle.transfers.filter((t) => t.onDelete).map((t) => t.source));
    const operations = new Map<string, Operation | null>();
    for (const t of lifecycle.transfers) {
        for (const [target, kind, op] of transferKinds(t)) {
            operations.set(`${t.origin.state}|${t.origin.trigger}|${t.origin.raw}|${kind}|${target}`, op);
        }
    }

    if (view === "csv") {
        for (const x of xStates) {
            if (nodes.some((n) => n.id === x.name)) {
                continue;
            }
            const state = lifecycle.states.get(x.name);
            nodes.push({
                id: x.name,
                label: x.label,
                stage: stageOf(x),
                initial: initial.has(x.name),
                deleted: state?.deleted ?? false,
                generated: false,
                exportsResources: state?.exportResources ?? false,
                protected: !deletable.has(x.name) && x.current !== null,
                selfLoops: [],
                desiredState: x.desiredState,
                title: x.annotations.web_label ?? x.name,
            });
            forEachTransfer(x, (trigger, raw, expr) => {
                if (expr === null || !byName.has(expr.target)) {
                    return;
                }
                const kind = TRIGGER_KIND[trigger];
                const lsmKind = expr.validate ? "validated" : kind;
                const operation =
                    operations.get(`${x.name}|${trigger}|${raw}|${lsmKind}|${expr.target}`) ??
                    operations.get(`${x.name}|${trigger}|${raw}|${kind}|${expr.target}`) ??
                    null;
                const detail: EdgeDetail = { kind, state: x.name, trigger, raw, validate: expr.validate, rollback: expr.rollback, operation };
                if (expr.target === x.name) {
                    const node = nodes[nodes.length - 1];
                    if (!node.selfLoops.includes(kind)) {
                        node.selfLoops.push(kind);
                    }
                    return;
                }
                addEdge(edges, x.name, expr.target, detail);
            });
        }
        const used = [...new Set(nodes.map((n) => n.stage))];
        return { view, nodes, edges: [...edges.values()], stages: stagesFor(used, metadata) };
    }

    if (view === "lsm") {
        for (const state of lifecycle.states.values()) {
            const origin = state.origin;
            const x = origin.kind === "csv" ? origin.xState : byName.get(origin.source);
            nodes.push({
                id: state.name,
                label: state.label,
                stage: x ? stageOf(x) : "",
                initial: initial.has(state.name),
                deleted: state.deleted,
                generated: origin.kind !== "csv",
                exportsResources: state.exportResources,
                protected: !deletable.has(state.name) && state.validateSelf !== null,
                selfLoops: [],
                desiredState: state.desiredState.onExport,
                title: state.annotations.web_label ?? state.name,
            });
        }
        const index = new Map(nodes.map((n) => [n.id, n]));
        for (const t of lifecycle.transfers) {
            for (const [target, kind, operation] of transferKinds(t)) {
                const parsed = t.origin.raw;
                const detail: EdgeDetail = {
                    kind,
                    state: t.origin.state,
                    trigger: t.origin.trigger,
                    raw: parsed,
                    validate: t.validate,
                    rollback: operation === "rollback",
                    operation,
                    description: t.description,
                };
                if (target === t.source) {
                    const node = index.get(target);
                    if (node && !node.selfLoops.includes(kind)) {
                        node.selfLoops.push(kind);
                    }
                    continue;
                }
                addEdge(edges, t.source, target, detail);
            }
        }
        const used = [...new Set(nodes.map((n) => n.stage))];
        return { view, nodes, edges: [...edges.values()], stages: stagesFor(used, metadata) };
    }

    // Desired states: one node per desired state value, the start and end of the lifecycle
    // are the desired states of the states without current attribute set
    const desired = new Map<string, XState[]>();
    for (const x of xStates) {
        desired.set(x.desiredState, [...(desired.get(x.desiredState) ?? []), x]);
    }
    for (const [name, members] of desired) {
        const labels = members.map((m) => m.label);
        nodes.push({
            id: name,
            label: labels.includes("success") ? "success" : members.some((m) => m.current !== null) ? "info" : null,
            stage: members[0].annotations.web_stage || (members.some((m) => m.current !== null) ? name : ""),
            initial: members.some((m) => initial.has(m.name)),
            deleted: members.every((m) => lifecycle.states.get(m.name)?.deleted),
            generated: false,
            exportsResources: members.some((m) => m.triggers.on_deployed.length > 0),
            protected: !members.some((m) => deletable.has(m.name)),
            selfLoops: [],
            desiredState: name,
            title: `${name} (${members.length} state${members.length === 1 ? "" : "s"})`,
        });
    }
    const index = new Map(nodes.map((n) => [n.id, n]));
    for (const x of xStates) {
        forEachTransfer(x, (trigger, raw, expr) => {
            const target = expr ? byName.get(expr.target) : undefined;
            if (!expr || !target) {
                return;
            }
            const kind = TRIGGER_KIND[trigger];
            const detail: EdgeDetail = { kind, state: x.name, trigger, raw, validate: expr.validate, rollback: expr.rollback, operation: null };
            if (target.desiredState === x.desiredState) {
                const node = index.get(x.desiredState);
                if (node && !node.selfLoops.includes(kind)) {
                    node.selfLoops.push(kind);
                }
                return;
            }
            addEdge(edges, x.desiredState, target.desiredState, detail);
        });
    }
    const used = [...new Set(nodes.map((n) => n.stage))];
    return { view, nodes, edges: [...edges.values()], stages: stagesFor(used, metadata) };
}
